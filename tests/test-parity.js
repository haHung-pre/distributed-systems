'use strict';
/**
 * Cross-implementation parity test.
 *
 * The CRDT exists twice: src/common/crdt/rga.js (Node, CommonJS) and
 * src/client/web/rga.browser.js (browser, IIFE on `window`). They MUST behave
 * identically or a browser client and a server replica would diverge.
 *
 * This test loads the browser file into a fake `window`, then drives both
 * implementations through the same randomised concurrent histories and
 * compares the resulting text, version vectors and element ordering.
 *
 *   node tests/test-parity.js
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const { RGA: NodeRGA } = require('../src/common/crdt/rga');

// --- load the browser implementation in a sandbox ---------------------------
const src = fs.readFileSync(path.join(__dirname, '../src/client/web/rga.browser.js'), 'utf8');
const sandbox = { window: {}, console };
vm.createContext(sandbox);
vm.runInContext(src, sandbox, { filename: 'rga.browser.js' });
const WebRGA = sandbox.window.RGA;

let pass = 0, fail = 0;
function check(name, cond, extra = '') {
  if (cond) { pass++; console.log(`  \x1b[32m✓\x1b[0m ${name}`); }
  else { fail++; console.log(`  \x1b[31m✗\x1b[0m ${name} ${extra}`); }
}
function mulberry(seed) { return function () { seed |= 0; seed = seed + 0x6D2B79F5 | 0; let t = Math.imul(seed ^ seed >>> 15, 1 | seed); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; }; }

console.log('\n\x1b[1m▍Node ↔ browser CRDT parity\x1b[0m');
check('browser implementation exposes RGA', typeof WebRGA === 'function');

// 1 — identical operations produced for identical local edits
{
  const n = new NodeRGA('site1'), w = new WebRGA('site1');
  const nOps = n.localInsertText(0, 'Hello world');
  const wOps = w.localInsertText(0, 'Hello world');
  check('same ops generated for the same edit', JSON.stringify(nOps) === JSON.stringify(wOps));
  n.localDeleteRange(5, 6); w.localDeleteRange(5, 6);
  check('same text after delete', n.text() === w.text(), `${n.text()} vs ${w.text()}`);
  check('same version vector', JSON.stringify(n.vv) === JSON.stringify(w.vv));
}

// 2 — randomised concurrent histories applied to both implementations
{
  let ok = true, sample = '';
  for (let seed = 0; seed < 40; seed++) {
    const rnd = mulberry(seed + 1000);
    // three logical sites; generate ops with the Node impl, then feed the same
    // shuffled stream into one Node replica and one browser replica.
    const gens = ['a', 'b', 'c'].map((s) => new NodeRGA(s));
    gens[0].localInsertText(0, 'shared base');
    const seedOps = [...gens[0].oplog];
    for (const g of gens.slice(1)) for (const op of seedOps) g.apply(op);
    const all = [...seedOps];
    for (const g of gens) {
      const k = 1 + Math.floor(rnd() * 5);
      for (let i = 0; i < k; i++) {
        if (rnd() < 0.7 || g.length === 0) all.push(...g.localInsertText(Math.floor(rnd() * (g.length + 1)), String.fromCharCode(97 + Math.floor(rnd() * 26))));
        else all.push(...g.localDeleteRange(Math.floor(rnd() * g.length), 1));
      }
    }
    const order = [...all].sort(() => rnd() - 0.5);
    const n = new NodeRGA('x'), w = new WebRGA('x');
    for (const op of order) { n.apply(op); w.apply(op); }
    if (n.text() !== w.text() || n.pendingCount() !== w.pendingCount()) {
      ok = false; sample = `seed=${seed} node=${JSON.stringify(n.text())} web=${JSON.stringify(w.text())}`; break;
    }
  }
  check('40 randomised histories produce identical text in both implementations', ok, sample);
}

// 3 — snapshot interoperability (server snapshot -> browser replica)
{
  const n = new NodeRGA('server');
  n.localInsertText(0, 'server side content');
  n.localDeleteRange(0, 7);
  const w = WebRGA.fromSnapshot('browser', n.snapshot());
  check('browser rebuilds a server snapshot identically', w.text() === n.text(), `${w.text()} vs ${n.text()}`);

  // and the browser can keep editing on top of it, with the server following
  const op = w.localInsert(w.idAtPosition(0), '>');
  n.apply(op);
  check('server applies an op generated by the browser', n.text() === w.text(), `${n.text()} vs ${w.text()}`);
}

console.log(`\n  ${pass} passed, ${fail} failed\n`);
process.exit(fail ? 1 : 0);
